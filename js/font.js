function glyph(ch) {
  return FONT[ch] || FONT['?'];
}
function glyphW(g) {
  let w = 0;
  for (const r of g) w = Math.max(w, r.length);
  return w;
}
function textW(str, scale) {
  str = String(str).toUpperCase();
  let w = 0;
  for (const ch of str) w += glyphW(glyph(ch)) + 1;
  return Math.max(0, w - 1) * scale;
}
// x,y in device pixels; scale = device px per font pixel (integer for crisp blocks)
function pixText(ctx, str, x, y, scale, color = '#fff', align = 'left') {
  str = String(str).toUpperCase();
  if (align !== 'left') {
    const w = textW(str, scale);
    if (align === 'center') x -= w / 2;
    else if (align === 'right') x -= w;
  }
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const yy = Math.round(y);
  for (const ch of str) {
    const g = glyph(ch);
    for (let r = 0; r < g.length; r++) {
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] === '#') ctx.fillRect(cx + c * scale, yy + r * scale, scale, scale);
      }
    }
    cx += (glyphW(g) + 1) * scale;
  }
}
